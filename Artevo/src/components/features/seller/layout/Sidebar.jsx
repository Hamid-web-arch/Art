export default function Sidebar({ isOpen, onClose }) {
  const navigate = useNavigate();
  const location = useLocation();

  const handleNavigate = (path) => {
    navigate(path);
    onClose?.();
  };

  return (
    <>
      {isOpen && (
        <div
          onClick={onClose}
          className="fixed inset-0 bg-black/40 z-40 lg:hidden"
        />
      )}

      <div
        className={`
          bg-[#F3F5F7] h-screen w-64 flex-shrink-0
          fixed lg:static top-0 left-0 z-50
          transform transition-transform duration-300 ease-in-out
          ${isOpen ? 'translate-x-0' : '-translate-x-full'}
          lg:translate-x-0
        `}
      >
        <button
          onClick={onClose}
          className="lg:hidden absolute top-4 right-4 text-gray-500 text-2xl"
        >
          ✕
        </button>

        <div className="space-y-4 mt-10 px-6 lg:ml-10 lg:px-0">
          <Logo />
          <nav className="flex flex-col gap-2 mt-10">
            {navItems.map((item) => {
              const paths=item.matchPaths || [item.path];
              const isActive =paths.some((p)=> location.pathname.startsWith(p)); 
              return (
                <div
                  key={item.path}
                  onClick={() => handleNavigate(item.path)}
                  className={`py-3 px-4 lg:px-8 rounded-lg lg:rounded-l-lg lg:rounded-r-none flex items-center gap-2 cursor-pointer transition-colors whitespace-nowrap ${
                    isActive
                      ? "bg-[#900B00] text-white"
                      : "text-[#9C9C9C] hover:text-[#5F5E5E]"
                  }`}
                >
                  {item.icon}
                  <span className="font-inter font-medium text-sm lg:text-base">{item.label}</span>
                </div>
              );
            })}
          </nav>
        </div>
      </div>
    </>
  );
}